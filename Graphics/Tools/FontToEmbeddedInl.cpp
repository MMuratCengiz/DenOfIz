#include <cstdint>
#include <cstring>
#include <fstream>
#include <iostream>
#include <iterator>
#include <miniz/miniz.h>
#include <vector>

int main( const int argc, char *argv[] )
{
    if ( argc != 3 )
    {
        std::cerr << "Usage: " << argv[ 0 ] << " <font file> <output.inl>\n";
        return 1;
    }

    std::ifstream input( argv[ 1 ], std::ios::binary );
    if ( !input )
    {
        std::cerr << "Cannot read " << argv[ 1 ] << "\n";
        return 1;
    }
    const std::vector<uint8_t> font( ( std::istreambuf_iterator<char>( input ) ), std::istreambuf_iterator<char>( ) );

    mz_ulong             compressedSize = mz_compressBound( static_cast<mz_ulong>( font.size( ) ) );
    std::vector<uint8_t> data( sizeof( uint32_t ) + compressedSize );
    const auto           fontSize = static_cast<uint32_t>( font.size( ) );
    std::memcpy( data.data( ), &fontSize, sizeof( uint32_t ) );
    if ( mz_compress2( data.data( ) + sizeof( uint32_t ), &compressedSize, font.data( ), static_cast<mz_ulong>( font.size( ) ), MZ_UBER_COMPRESSION ) != MZ_OK )
    {
        std::cerr << "Compression failed\n";
        return 1;
    }
    data.resize( sizeof( uint32_t ) + compressedSize );

    std::ofstream out( argv[ 2 ] );
    out << "// Generated by FontToEmbeddedInl from " << argv[ 1 ] << ", do not edit.\n\n";
    out << "const uint8_t g_DefaultFontCompressed[] = {";
    for ( size_t i = 0; i < data.size( ); ++i )
    {
        out << ( i % 20 == 0 ? "\n    " : " " ) << static_cast<uint32_t>( data[ i ] ) << ",";
    }
    out << "\n};\n\nconst size_t g_DefaultFontCompressedSize = " << data.size( ) << ";\n";
    std::cout << argv[ 1 ] << ": " << font.size( ) << " -> " << data.size( ) << " bytes\n";
    return out ? 0 : 1;
}
